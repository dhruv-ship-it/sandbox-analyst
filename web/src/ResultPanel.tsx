import { traceUrl } from "./api";
import { CodeBlock } from "./CodeBlock";
import { EvidenceList } from "./EvidenceList";
import { StatusBadge } from "./StatusBadge";
import type { RunSummary } from "./types";
import { formatElapsed } from "./utils";

const STATUS_MESSAGES: Record<string, string> = {
  answered: "Answered, and every value was verified against the script's own output.",
  failed: "The model never produced an answer that could be verified against the script's output.",
  repeated_failure: "The model kept repeating the same failing code, so the run was stopped early.",
  tool_failure: "The sandbox itself ran into trouble, so the run was stopped.",
  budget_exceeded: "This run used up its time or token budget before finishing.",
  llm_error: "The language model provider was unavailable, so the run was stopped.",
  error: "Something unexpected went wrong while running this.",
};

export function ResultPanel({ summary }: { summary: RunSummary }): JSX.Element {
  const message = STATUS_MESSAGES[summary.status] ?? "This run ended with an unrecognized status.";

  return (
    <section aria-labelledby="result-heading" className="result-panel">
      <h2 id="result-heading">Result</h2>
      <StatusBadge status={summary.status} />
      <p>{message}</p>

      {summary.answers.length > 0 && (
        <dl className="answer-list">
          {summary.answers.map((answer) => (
            <div key={answer.name} className="answer-row">
              <dt>{answer.name}</dt>
              <dd>{answer.value}</dd>
            </div>
          ))}
        </dl>
      )}

      {summary.explanation !== "" && <p className="explanation">{summary.explanation}</p>}

      <EvidenceList items={summary.evidence} />

      {summary.chart_urls.length > 0 && (
        <div className="chart-images">
          {summary.chart_urls.map((url) => (
            <img key={url} src={url} alt="Chart generated by the analysis script" />
          ))}
        </div>
      )}

      {summary.code !== "" && (
        <div className="final-code">
          <h3>Final code</h3>
          <CodeBlock code={summary.code} showCopy />
        </div>
      )}

      <dl className="stats">
        <div>
          <dt>Attempts</dt>
          <dd>{summary.attempts.length}</dd>
        </div>
        <div>
          <dt>Tokens</dt>
          <dd>{summary.prompt_tokens + summary.completion_tokens}</dd>
        </div>
        <div>
          <dt>Time</dt>
          <dd>{formatElapsed(summary.latency_ms)}</dd>
        </div>
      </dl>

      <a href={traceUrl(summary.run_id)} download={`${summary.run_id}.jsonl`}>
        Download trace (JSONL)
      </a>
    </section>
  );
}
